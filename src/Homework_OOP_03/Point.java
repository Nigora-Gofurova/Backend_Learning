package Homework_OOP_03;

public class Point {
    private double x;
    private double y;
    private double z;

    public Point(double x, double y, double z) {
        this.x = x;
        this.y = y;
        this.z = z;
    }

    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }

    public double getZ() {
        return z;
    }

    public void printInfo() {
        System.out.println("Point(x=" + x + ", y=" + y + ", z=" + z + ")");
    }
}
